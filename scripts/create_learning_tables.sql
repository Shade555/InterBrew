-- Core learning and user-profile tables used by the scenario, dashboard,
-- profile, lesson, quiz, and certification features.
-- Run after Supabase Auth is enabled.

CREATE EXTENSION IF NOT EXISTS "pgcrypto";

CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text,
  email text,
  role text,
  domain text,
  avatar_url text,
  badges jsonb NOT NULL DEFAULT '[]'::jsonb,
  xp integer NOT NULL DEFAULT 0,
  daily_xp integer NOT NULL DEFAULT 0,
  interviews_taken integer NOT NULL DEFAULT 0,
  streak integer NOT NULL DEFAULT 0,
  last_activity jsonb NOT NULL DEFAULT '{}'::jsonb,
  dashboard_graph jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.scenarios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text,
  difficulty text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.modules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_id bigint REFERENCES public.scenarios(id) ON DELETE CASCADE,
  title text NOT NULL,
  description text,
  difficulty text,
  order_number integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.lessons (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_id bigint NOT NULL REFERENCES public.modules(id) ON DELETE CASCADE,
  title text NOT NULL,
  content text,
  video_url text,
  order_number integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.quizzes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lesson_id bigint NOT NULL REFERENCES public.lessons(id) ON DELETE CASCADE,
  question text NOT NULL,
  options jsonb NOT NULL DEFAULT '[]'::jsonb,
  correct_answer text,
  question_type text NOT NULL DEFAULT 'mcq',
  explanation text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.certifications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  title text NOT NULL,
  issuer text NOT NULL DEFAULT 'InterBrew',
  issue_date date NOT NULL DEFAULT current_date,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, title)
);

CREATE TABLE IF NOT EXISTS public.feedback (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
  module_id bigint REFERENCES public.modules(id) ON DELETE SET NULL,
  score integer,
  feedback_text text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_modules_scenario_id
  ON public.modules(scenario_id);
CREATE INDEX IF NOT EXISTS idx_lessons_module_id
  ON public.lessons(module_id);
CREATE INDEX IF NOT EXISTS idx_quizzes_lesson_id
  ON public.quizzes(lesson_id);
CREATE INDEX IF NOT EXISTS idx_certifications_user_id
  ON public.certifications(user_id);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scenarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.modules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lessons ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.quizzes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.certifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.feedback ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public can read learning content" ON public.scenarios;
CREATE POLICY "Public can read learning content"
  ON public.scenarios FOR SELECT USING (true);
DROP POLICY IF EXISTS "Public can read modules" ON public.modules;
CREATE POLICY "Public can read modules"
  ON public.modules FOR SELECT USING (true);
DROP POLICY IF EXISTS "Public can read lessons" ON public.lessons;
CREATE POLICY "Public can read lessons"
  ON public.lessons FOR SELECT USING (true);
DROP POLICY IF EXISTS "Public can read quizzes" ON public.quizzes;
CREATE POLICY "Public can read quizzes"
  ON public.quizzes FOR SELECT USING (true);

DROP POLICY IF EXISTS "Users can read own profile" ON public.profiles;
CREATE POLICY "Users can read own profile"
  ON public.profiles FOR SELECT USING (auth.uid() = id);
DROP POLICY IF EXISTS "Users can insert own profile" ON public.profiles;
CREATE POLICY "Users can insert own profile"
  ON public.profiles FOR INSERT WITH CHECK (auth.uid() = id);
DROP POLICY IF EXISTS "Users can update own profile" ON public.profiles;
CREATE POLICY "Users can update own profile"
  ON public.profiles FOR UPDATE
  USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Users can read own certifications" ON public.certifications;
CREATE POLICY "Users can read own certifications"
  ON public.certifications FOR SELECT USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can create own certifications" ON public.certifications;
CREATE POLICY "Users can create own certifications"
  ON public.certifications FOR INSERT WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can manage own feedback" ON public.feedback;
CREATE POLICY "Users can manage own feedback"
  ON public.feedback FOR ALL
  USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
